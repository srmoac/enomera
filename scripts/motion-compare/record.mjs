import { createRequire } from 'node:module'; const { chromium } = createRequire(import.meta.url)('playwright');
import fs from 'node:fs';
const [name, port, vp] = process.argv.slice(2);
const size = vp === 'm390' ? { width: 390, height: 844 } : { width: 1440, height: 900 };
const mobile = vp === 'm390';
const b = await chromium.launch();
const dir = `vid/${vp}-${process.argv[5]||name}`; fs.rmSync(dir, { recursive: true, force: true });
const ctx = await b.newContext({ viewport: size, deviceScaleFactor: 1, isMobile: mobile, hasTouch: mobile, recordVideo: { dir, size } });
const p = await ctx.newPage(); const t0 = Date.now();
await p.goto(`http://localhost:${port}/`, { waitUntil: 'networkidle' });
await p.evaluate(() => document.fonts.ready); await p.waitForTimeout(1500);
const startAt = (Date.now() - t0) / 1000;
await p.evaluate(() => {
  window.__log = []; const t0 = performance.now();
  const tick = () => { window.__log.push([Math.round(performance.now() - t0), Math.round(scrollY), ...[...document.querySelectorAll('.journey-petal')].flatMap(e => { const r = e.getBoundingClientRect(); return [Math.round(r.left), Math.round(r.top)]; })]); requestAnimationFrame(tick); };
  requestAnimationFrame(tick);
  // time-driven native scroll (1x real time); returns when done
  window.__scroll = (to, ms, ease = 'io') => new Promise(res => { const from = scrollY, s = performance.now();
    const f = { io: t => t < .5 ? 2 * t * t : 1 - 2 * (1 - t) ** 2, lin: t => t, out: t => 1 - (1 - t) ** 2, in: t => t * t }[ease];
    const step = () => { const t = Math.min(1, (performance.now() - s) / ms); scrollTo({ top: from + (to - from) * f(t), behavior: 'instant' }); t < 1 ? requestAnimationFrame(step) : res(); }; requestAnimationFrame(step); });
});
const S = (to, ms, ease) => p.evaluate(([to, ms, ease]) => window.__scroll(to, ms, ease), [to, ms, ease]);
const top = sel => p.evaluate(s => Math.round(document.querySelector(s).getBoundingClientRect().top + scrollY), sel);
const end = await p.evaluate(() => document.documentElement.scrollHeight - innerHeight);
const off = mobile ? 90 : 130;
const yE = await top('#etha') - off, yA = await top('#ambo') - off, yM = await top('#minne') - off, yC = await top('#combinacao') - off;
const tap = async sel => { const l = p.locator(sel).first(); if (await l.count() && await l.isVisible()) { mobile ? await l.tap() : await l.click(); return true; } return false; };
const marks = []; const mark = n => marks.push([n, Date.now() - t0]);
mark('descida completa'); await S(end, 13000, 'lin'); await p.waitForTimeout(1200);
mark('volta ao topo'); await S(0, 2500); await p.waitForTimeout(900);
mark('etha + pausa'); await S(yE, 3200); await p.waitForTimeout(1400);
mark('reversão antes de parar'); await S(yE + (yA - yE) * .6, 1300, 'in'); await S(yE + (yA - yE) * .25, 700, 'out'); 
mark('ambo'); await S(yA, 2400); await p.waitForTimeout(1200);
mark('interação ambo'); await tap('#ambo-demo [data-ambo="next"]'); await p.waitForTimeout(700); await tap('#ambo-demo [data-mode]:not([aria-pressed="true"])'); await p.waitForTimeout(250); await tap('#ambo-demo [data-mode]:not([aria-pressed="true"])'); await p.waitForTimeout(900);
mark('minne'); await S(yM, 2600); await p.waitForTimeout(1200);
mark('interação minne'); await tap('#minne-demo [data-mini="Agenda"]'); await p.waitForTimeout(700); await tap('#minne-demo [data-mini="Pacientes"]'); await p.waitForTimeout(200); await tap('#minne-demo [data-mini="Meu dia"]'); await p.waitForTimeout(900);
mark('combinação'); await S(yC + (mobile ? 250 : 0), 3600); await p.waitForTimeout(1000);
mark('seleção'); await tap('#service-options [data-service="etha"]'); await p.waitForTimeout(900); await tap('#service-options [data-service="etha"]'); await p.waitForTimeout(900);
mark('fechamento'); await S(end, 3200); await p.waitForTimeout(2000);
const log = await p.evaluate(() => window.__log);
const total = (Date.now() - t0) / 1000;
await ctx.close(); await b.close();
const f = fs.readdirSync(dir).find(x => x.endsWith('.webm'));
fs.writeFileSync(`${dir}/meta.json`, JSON.stringify({ video: `${dir}/${f}`, startAt, total, marks, anchors: { yE, yA, yM, yC, end }, log }));
console.log(name, vp, 'start', startAt.toFixed(2), 'total', total.toFixed(1), 'frames logged', log.length, JSON.stringify({ yE, yA, yM, yC, end }));
