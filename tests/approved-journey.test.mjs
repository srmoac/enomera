import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { getDb, closeDb } from '../server/db.mjs';
import { createEnomeraServer } from '../scripts/server.mjs';

test('Approved journey persists selection, activates once, isolates portraits and publishes an explicit snapshot', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(),'enomera-approved-'));
  process.env.ENOMERA_DB_PATH = path.join(dir,'db.sqlite');
  process.env.ENOMERA_STORAGE_DIR = path.join(dir,'private');
  process.env.ENOMERA_REQUIRE_REMOTE_INFRA = 'false';
  const db = await getDb(process.env.ENOMERA_DB_PATH);
  const server = createEnomeraServer(db);
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = async (route,method='GET',body=null,token=null,headers={}) => {
    const res = await fetch(base+route,{method,headers:{...(body?{'Content-Type':'application/json'}:{}),...(token?{Authorization:`Bearer ${token}`} :{}),...headers},body:body?JSON.stringify(body):undefined});
    return {status:res.status, data:res.headers.get('content-type')?.includes('application/json')?await res.json():null};
  };
  const codeFor = async email => (await request(`/api/v1/dev/outbox?recipient=${encodeURIComponent(email)}`)).data.messages[0].body_preview.match(/\d{6}/)[0];
  try {
    const email = 'preview.primary@exemplo.invalid';
    const signup = await request('/api/v1/auth/signup','POST',{fullName:'Profissional de teste',email,password:'SenhaFicticia!2026',selection:{products:['ambo','minne'],ethaFormat:'one_page'}});
    assert.equal(signup.status,201);
    const token = signup.data.sessionToken;
    const slug = signup.data.account.slug;
    assert.deepEqual((await request('/api/v1/commercial/selection','GET',null,token)).data.selection.products,['ambo','minne']);
    assert.equal((await request('/api/v1/commercial/orders','POST',{products:['ambo']},token,{'X-Idempotency-Key':'unverified'})).status,403);
    const second = await request('/api/v1/auth/signup','POST',{fullName:'Outra profissional',email:'preview.other@exemplo.invalid',password:'SenhaFicticia!2026'});
    const other = second.data.sessionToken;
    const corrected = 'preview.corrected@exemplo.invalid';
    assert.equal((await request('/api/v1/auth/change-email','POST',{email:corrected},token)).status,200);
    assert.equal((await request('/api/v1/auth/verify-email','POST',{email,code:await codeFor(email)},token)).status,400);
    const verified = await request('/api/v1/auth/verify-email','POST',{email:corrected,code:await codeFor(corrected)},token);
    assert.equal(verified.status,200);
    assert.equal((await request('/api/v1/auth/resend-verification','POST',{email:corrected},token)).status,429);
    const login = await request('/api/v1/auth/login','POST',{email:corrected,password:'SenhaFicticia!2026'});
    assert.deepEqual((await request('/api/v1/commercial/selection','GET',null,login.data.sessionToken)).data.selection.products,['ambo','minne']);
    await request('/api/v1/commercial/selection','PUT',{products:['ambo','minne','etha'],ethaFormat:'one_page'},token);
    const orders = await Promise.all(Array.from({length:4},()=>request('/api/v1/commercial/orders','POST',{products:['ambo','minne','etha'],simulatedOutcome:'approved'},token,{'X-Idempotency-Key':'concurrent-same-checkout'})));
    assert.ok(orders.every(r=>[200,201].includes(r.status)),JSON.stringify(orders.map(r=>r.status)));
    assert.equal(new Set(orders.map(r=>r.data.order.id)).size,1);
    assert.equal(orders[0].data.order.due_today_cents,0);
    assert.equal((await db.get('SELECT COUNT(*) AS c FROM commercial_orders WHERE account_id = ?',signup.data.account.id)).c,1);
    const declined = await request('/api/v1/commercial/orders','POST',{products:['ambo'],simulatedOutcome:'declined'},token,{'X-Idempotency-Key':'retry-approved-selection'});
    await request('/api/v1/commercial/selection','PUT',{products:['ambo'],stage:'review'},token);
    assert.equal((await request(`/api/v1/commercial/orders/${declined.data.order.id}/retry`,'POST',{simulatedOutcome:'approved'},token)).status,200);
    const resumed = (await request('/api/v1/commercial/selection','GET',null,token)).data.selection;
    assert.equal(resumed.stage,'confirmed');
    assert.deepEqual(resumed.products,['ambo']);
    assert.equal((await request(`/api/v1/public/sites/${slug}`)).status,404);
    const png = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jJZkAAAAASUVORK5CYII=';
    const photo = await request('/api/v1/etha/project/photo','POST',{originalName:'foto.png',contentBase64:png},token);
    assert.equal(photo.status,200);
    assert.equal((await request(photo.data.photoUrl)).status,401);
    assert.equal((await request(photo.data.photoUrl,'GET',null,other)).status,403);
    const firstDraft = await request('/api/v1/etha/project/editor','POST',{content:{displayName:'Profissional de teste',headline:'Primeira versão',photoAssetId:photo.data.photoAssetId}},token);
    assert.equal(firstDraft.status,201);
    const published = await request('/api/v1/etha/project/publish-staging','POST',{versionId:firstDraft.data.versionId,ctaMode:'ambo'},token);
    assert.equal(published.status,200);
    const before = await request(`/api/v1/public/sites/${slug}`);
    assert.equal(before.data.headline,'Primeira versão');
    assert.equal(before.data.amboProfileSlug,slug);
    assert.equal((await request(before.data.photoUrl)).status,200);
    const draft = await request('/api/v1/etha/project/editor','POST',{content:{headline:'Segunda versão',photoAssetId:null}},token);
    assert.equal((await request(`/api/v1/public/sites/${slug}`)).data.photoAssetId,photo.data.photoAssetId);
    assert.equal((await request(`/api/v1/public/sites/${slug}`)).data.headline,'Primeira versão');
    await request('/api/v1/etha/project/publish-staging','POST',{versionId:draft.data.versionId},token);
    const after = await request(`/api/v1/public/sites/${slug}`);
    assert.equal(after.data.headline,'Segunda versão');
    assert.equal(after.data.photoUrl,null);
    assert.equal((await request(before.data.photoUrl)).status,404);
    await request('/api/v1/auth/logout','POST',{},token);
    assert.equal((await request('/api/v1/auth/me','GET',null,token)).status,401);
  } finally {
    await new Promise(resolve=>server.close(resolve));
    await closeDb();
    fs.rmSync(dir,{recursive:true,force:true});
  }
});
